"""Export the trained MNIST model to ``web/model.js`` for the in-browser demo.

Weights are quantized to 8-bit integers with one float scale per output neuron
(``W[:, j] ~= q[:, j] * scale[j]``), cutting the download from ~940 KB of
float32 to ~240 KB. The script reports test accuracy before and after
quantization so the trade-off is measured, not assumed.

    python examples/mnist.py        # trains and saves data/mnist_mlp.npz
    python web/export_model.py      # writes web/model.js
"""
import base64
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from tinynet.datasets import load_mnist  # noqa: E402

LAYER_KEYS = ["0", "3", "6"]  # Dense layers in examples/mnist.py (ReLU/Dropout have no weights)


def quantize(W: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    scale = np.abs(W).max(axis=0) / 127.0
    scale[scale == 0] = 1.0
    q = np.clip(np.round(W / scale), -127, 127).astype(np.int8)
    return q, scale.astype(np.float32)


def forward(X, layers):
    for i, (W, b) in enumerate(layers):
        X = X @ W + b
        if i < len(layers) - 1:
            X = np.maximum(X, 0)
    return X


def main():
    weights = dict(np.load(os.path.join(ROOT, "data", "mnist_mlp.npz")))
    _, _, X_test, y_test = load_mnist(os.path.join(ROOT, "data", "mnist"), download=False)

    float_layers = [(weights[f"{k}.W"], weights[f"{k}.b"]) for k in LAYER_KEYS]
    quant = [quantize(W) for W, _ in float_layers]
    q_layers = [(q.astype(np.float32) * s, b) for (q, s), (_, b) in zip(quant, float_layers)]

    acc_float = float(np.mean(forward(X_test, float_layers).argmax(1) == y_test))
    acc_q = float(np.mean(forward(X_test, q_layers).argmax(1) == y_test))
    print(f"test accuracy  float32: {acc_float:.2%}   int8: {acc_q:.2%}")

    # One clearly-written, correctly classified example per digit, for the "try an example"
    # buttons and as reference outputs that the browser implementation is checked against.
    logits_q = forward(X_test, q_layers)
    probs = np.exp(logits_q - logits_q.max(1, keepdims=True))
    probs /= probs.sum(1, keepdims=True)
    samples = []
    for d in range(10):
        i = int(np.flatnonzero((y_test == d) & (logits_q.argmax(1) == d) & (probs[:, d] > 0.9))[0])
        px = np.round(X_test[i] * 255).astype(np.uint8)
        logits = forward(px.astype(np.float32)[None] / 255.0, q_layers)[0]
        samples.append({"label": d, "pixels": base64.b64encode(px.tobytes()).decode(),
                        "logits": [round(float(v), 4) for v in logits]})

    model = {
        "architecture": "784-256-128-10 MLP, ReLU, trained from scratch with tinynet",
        "test_accuracy": round(acc_q, 4),
        "layers": [{"in": W.shape[0], "out": W.shape[1],
                    "w": base64.b64encode(q.tobytes()).decode(),  # row-major (in, out) int8
                    "scale": [float(v) for v in s],
                    "b": [round(float(v), 6) for v in b]}
                   for (q, s), (W, b) in zip(quant, float_layers)],
        "samples": samples,
    }
    out = os.path.join(ROOT, "web", "model.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by web/export_model.py - do not edit by hand.\n")
        f.write("window.TINYNET_MODEL = " + json.dumps(model, separators=(",", ":")) + ";\n")
    print(f"wrote {out} ({os.path.getsize(out) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
